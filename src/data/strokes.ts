import type { JointAngles, PhaseKeyframe, StrokeProfile, StrokeType } from "@/types/biomechanics";

/**
 * Neutral athletic ready stance.
 * Joint angles are right-handed canonical. Left-handed strokes set
 * `handedness: "left"` and the skeleton mirrors yaw/twist + laterality.
 *
 * Angle meanings (see `computeSkeletonPose`):
 * - shoulderFlexion: 0 hang → 90 forward horizontal → 180 up
 * - shoulderAbduction: 0 at side → 90 T-pose
 * - elbowFlexion: 0 straight → 90 right angle
 * - hipYaw: RH forehand coils negative (hitting side back), opens positive
 * - racketPathElevation: pitches racket head up(+)/down(-) from forearm
 */
export const READY: JointAngles = {
  hipYaw: 0,
  hipPitch: 0,
  spineTwist: 0,
  spineLean: 5,
  shoulderFlexion: 45,
  shoulderAbduction: 25,
  shoulderInternalRotation: 0,
  elbowFlexion: 60,
  wristExtension: 15,
  wristUlnarDeviation: 0,
  leadKneeFlexion: 28,
  trailKneeFlexion: 28,
  leadHipFlexion: 22,
  trailHipFlexion: 22,
  ankleDorsiflexion: 10,
  nonHittingShoulderFlexion: 35,
  nonHittingElbowFlexion: 55,
  racketFaceAngle: 0,
  racketPathElevation: 40,
};

function j(partial: Partial<JointAngles>): JointAngles {
  return { ...READY, ...partial };
}

function kf(
  phase: PhaseKeyframe["phase"],
  t: number,
  durationMs: number,
  joints: Partial<JointAngles>,
  racketSpeedMs: number,
  spinRpm: number,
  coachingCue: string,
): PhaseKeyframe {
  return {
    phase,
    t,
    durationMs,
    joints: j(joints),
    racketSpeedMs,
    spinRpm,
    coachingCue,
  };
}

