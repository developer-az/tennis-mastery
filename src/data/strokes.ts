/** Neutral athletic ready stance */
export const READY: JointAngles = {
  hipYaw: 0,
  hipPitch: 0,
  spineTwist: 0,
  spineLean: 5,
  shoulderFlexion: 20,
  shoulderAbduction: 15,
  shoulderInternalRotation: 0,
  elbowFlexion: 40,
  wristExtension: 10,
  wristUlnarDeviation: 0,
  leadKneeFlexion: 25,
  trailKneeFlexion: 25,
  leadHipFlexion: 20,
  trailHipFlexion: 20,
  ankleDorsiflexion: 10,
  nonHittingShoulderFlexion: 25,
  nonHittingElbowFlexion: 45,
  racketFaceAngle: 0,
  racketPathElevation: 0,
};

function j(partial: Partial<JointAngles>): JointAngles {
  return { ...READY, ...partial };
}

function kf(
  phase: PhaseKeyframe["phase"],
  t: number,
  durationMs: number,
  joints: Partial<JointAngles>,
  racketSpeedMs: number,
  spinRpm: number,
  coachingCue: string,
): PhaseKeyframe {
  return {
    phase,
    t,
    durationMs,
    joints: j(joints),
    racketSpeedMs,
    spinRpm,
    coachingCue,
  };
}

